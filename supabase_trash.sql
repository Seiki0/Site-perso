-- The app has no user authentication, so its trash is shared by all visitors.
create table if not exists public.trash_items (
  id bigint generated by default as identity primary key,
  item_type text not null check (item_type in ('note', 'file')),
  item_key text not null,
  deleted_at timestamptz not null default now(),
  unique (item_type, item_key)
);

alter table public.trash_items enable row level security;

grant select, insert, update, delete on public.trash_items to anon, authenticated;
grant usage, select on sequence public.trash_items_id_seq to anon, authenticated;

drop policy if exists "Anyone can read trash items" on public.trash_items;
create policy "Anyone can read trash items"
  on public.trash_items
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Anyone can add trash items" on public.trash_items;
create policy "Anyone can add trash items"
  on public.trash_items
  for insert
  to anon, authenticated
  with check (true);

drop policy if exists "Anyone can update trash items" on public.trash_items;
create policy "Anyone can update trash items"
  on public.trash_items
  for update
  to anon, authenticated
  using (true)
  with check (true);

drop policy if exists "Anyone can remove trash items" on public.trash_items;
create policy "Anyone can remove trash items"
  on public.trash_items
  for delete
  to anon, authenticated
  using (true);
